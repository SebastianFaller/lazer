#!/bin/sh
# Check that an x86-64 build of this branch compiles exactly the code of
# upstream lazer (lazer-crypto/lazer) and its labrados submodule.
#
#   scripts/check_x86_identical.sh UPSTREAM_DIR [FORK_DIR]
#
# UPSTREAM_DIR: a checkout of upstream lazer (with `git submodule update --init`)
# at the commit this branch is based on; FORK_DIR defaults to this checkout.
# Every C/C++ translation unit of the library (lazer, lattice-hash, labrados at
# LOGQ 32/36/38, the cffi headers) is preprocessed with the x86-64 flags of the
# build, in both trees, and the outputs (without line markers and blank lines)
# must be identical. Run it on x86-64, or elsewhere with an x86-64 cross target:
#   CC="clang -target x86_64-linux-gnu" CXX="clang++ -target x86_64-linux-gnu" ...
# X86FLAGS defaults to -march=native on x86-64 (use an AVX-512 machine, or pass
# e.g. X86FLAGS="-march=icelake-server").
set -e
UP=$(cd "$1" && pwd)
FORK=$(cd "${2:-$(dirname "$0")/..}" && pwd)
CC=${CC:-cc}
CXX=${CXX:-c++}
X86FLAGS=${X86FLAGS:--march=native}
EXTRA=${EXTRA_CPPFLAGS:-}
W=$(mktemp -d)
trap 'rm -rf "$W"' EXIT

# third-party headers (identical in both trees): Falcon and HEXL
(cd "$W" && unzip -q "$UP/third_party/Falcon-impl-20211101.zip" && unzip -q "$UP/third_party/hexl-development.zip")
FALCON=$W/Falcon-impl-20211101
HEXLINC=$W/hexl-development/hexl/include
# generated by HEXL's CMake (GCC build)
sed -e 's/^#cmakedefine HEXL_USE_GNU$/#define HEXL_USE_GNU/' -e 's/^#cmakedefine \(.*\)$/\/* #undef \1 *\//' \
  "$HEXLINC/hexl/util/defines.hpp.in" > "$HEXLINC/hexl/util/defines.hpp"

e() {  # e OUT CMD...: run the preprocessor CMD, abort on errors, normalize into OUT
  out=$1; shift
  "$@" > "$W/tmp.i" || { echo "preprocessing failed: $*" >&2; exit 2; }
  sed -e '/^[[:space:]]*$/d' "$W/tmp.i" > "$out"
}

pp() {  # pp TREE OUT: preprocess every translation unit of TREE into OUT/
  T=$1; O=$2; mkdir -p "$O"
  e "$O/lazer.c" $CC -E -P $X86FLAGS $EXTRA -DNDEBUG -DFALCON_FPNATIVE -DFALCON_AVX2 -DFALCON_FMA \
    -I"$T" -I"$T/src" -I"$FALCON" "$T/src/lazer.c"
  e "$O/hash.c" $CC -E -P $X86FLAGS $EXTRA -DNDEBUG -I"$T/src/lattice-hash/src" -I"$HEXLINC" \
    "$T/src/lattice-hash/src/hash.c"
  e "$O/hexl_wrapper.cpp" $CXX -E -P $X86FLAGS $EXTRA -DNDEBUG -I"$T/src/lattice-hash/src" -I"$HEXLINC" \
    "$T/src/lattice-hash/src/hexl_wrapper.cpp"
  for h in "$T"/src/labrado*_py.h; do
    e "$O/$(basename "$h")" $CC -E -P $X86FLAGS $EXTRA -x c "$h"
  done
  for q in 32 36 38; do
    for c in "$T"/src/labrados/*.c; do
      case $(basename "$c") in test_*|bench_*|aggsig.c|falcon_poly.c) continue ;; esac
      e "$O/labrados_${q}_$(basename "$c")" $CC -E -P -std=gnu2x $X86FLAGS $EXTRA -DNDEBUG -DLOGQ=$q \
        -I"$T/src/labrados" "$c"
    done
  done
}

(cd "$UP" && make -s lazer.h >/dev/null)
(cd "$FORK" && make -s lazer.h >/dev/null)
pp "$UP" "$W/up"
pp "$FORK" "$W/fork"
if diff -r -q "$W/up" "$W/fork" > "$W/diff.txt"; then
  echo "x86-64: all $(ls "$W/up" | wc -l | tr -d ' ') preprocessed translation units are identical to upstream"
else
  cat "$W/diff.txt"
  for f in $(sed -n 's/^Files .*\/up\/\([^ ]*\) and .*/\1/p' "$W/diff.txt"); do
    echo "=== $f"; diff "$W/up/$f" "$W/fork/$f" | head -20
  done
  exit 1
fi
